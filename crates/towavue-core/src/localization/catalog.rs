//! English and Japanese catalog. Every key requires both translations.
use super::Language;

macro_rules! messages {
    ($($key:ident => ($english:literal, $japanese:literal),)*) => {
        #[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
        pub enum Text { $($key,)* }

        impl Text {
            pub const fn in_language(self, language: Language) -> &'static str {
                match (self, language) {
                    $((Self::$key, Language::English) => $english,
                      (Self::$key, Language::Japanese) => $japanese,)*
                }
            }
        }
    };
}

