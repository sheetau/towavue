"""Generate pinned Fluent paths offline using only the Python standard library."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "crates/towavue-app/assets/fluent"
OUTPUT = ROOT / "crates/towavue-app/src/fluent/paths.rs"


def number(value):
    result = f"{value:.8g}" if abs(value) >= 1e-8 else "0"
    return result + ".0" if "." not in result and "e" not in result else result


def parse(data):
    token = r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?"
    assert not re.sub(token, "", data).replace(",", "").strip()
    tokens = re.findall(token, data)
    current, initial, command = (0, 0), (0, 0), None
    while tokens:
        if tokens[0].isalpha():
            command = tokens.pop(0)
        # Fail closed on new SVG syntax instead of silently changing artwork.
        assert command in ("M", "L", "H", "V", "C", "Z"), command
        if command == "Z":
            yield "close", ()
            current, command = initial, None
            continue
        count = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6}[command]
        values = tuple(float(tokens.pop(0)) for _ in range(count))
        if command == "H":
            current = values[0], current[1]
            yield "line_to", current
        elif command == "V":
            current = current[0], values[0]
            yield "line_to", current
        else:
            current = values[-2:]
            yield {"M": "move_to", "L": "line_to", "C": "cubic_to"}[command], values
            if command == "M":
                initial, command = current, "L"


def generate():
    manifest = json.loads((ASSETS / "upstream.json").read_text(encoding="utf-8"))
    for name, digest in manifest["sha256"].items():
        assert hashlib.sha256((ASSETS / name).read_bytes()).hexdigest() == digest, name
    lines = ["// Generated by scripts/generate-fluent-paths.py; do not edit.",
             "// Fluent SVG source and license: assets/fluent/README.md.",
             "use super::Kind;", "use tiny_skia::{Path, PathBuilder};",
             "pub(super) fn paths(kind: Kind) -> Vec<Path> {", "match kind {"]
    for kind, source in manifest["icons"].items():
        svg = ET.parse(ASSETS / source.rsplit("/", 1)[-1]).getroot()
        assert svg.attrib["viewBox"] == "0 0 16 16"
        lines.append(f"Kind::{kind} => vec![")
        for element in svg:
            assert element.tag.split("}")[-1] == "path"
            assert set(element.attrib) == {"d", "fill"}
            assert element.attrib["fill"] == "#212121"
            lines.append("{ let mut path = PathBuilder::new();")
            for method, values in parse(element.attrib["d"]):
                lines.append(f"path.{method}({', '.join(number(v) for v in values)});")
            lines.append('path.finish().expect("pinned Fluent path") },')
        lines.append("],")
    lines.extend(["}", "}"])
    return subprocess.run(["rustfmt", "--emit", "stdout", "--edition", "2024"],
                          input="\n".join(lines), capture_output=True, text=True,
                          check=True, cwd=ROOT).stdout.replace("\r\n", "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    generated = generate().encode("utf-8")
    if options.check:
        assert OUTPUT.read_bytes() == generated, "Fluent paths need regeneration"
        print("Pinned SVG hashes and generated Fluent paths match.")
    else:
        OUTPUT.parent.mkdir(exist_ok=True)
        OUTPUT.write_bytes(generated)
